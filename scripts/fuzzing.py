#!/usr/bin/env -S uv run --script
"""Execute bounded semantic corpus replay or instrumented fuzzing campaigns."""

import argparse
import hashlib
import json
import os
import pathlib
import random
import re
import shutil
import signal
import subprocess
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGETS = ("trailers", "snapshots", "descriptions")
MAX_INPUT = 4096
NIGHTLY = "nightly-2026-10-14"
FUZZ_VERSION = "0.13.2"


def execute(
    command: list[str],
    log: pathlib.Path,
    timeout: int = 300,
    environment: dict[str, str] | None = None,
) -> int:
    """Retain complete diagnostic output, including unsuccessful executions."""
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("w") as output:
        output.write(json.dumps(command) + "\n")
        output.flush()
        with subprocess.Popen(
            command,
            cwd=ROOT,
            stdout=output,
            stderr=subprocess.STDOUT,
            env=environment,
            start_new_session=True,
        ) as process:
            try:
                return process.wait(timeout=timeout)
            except subprocess.TimeoutExpired:
                try:
                    os.killpg(process.pid, signal.SIGTERM)
                except ProcessLookupError:
                    pass
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    pass
                finally:
                    try:
                        os.killpg(process.pid, signal.SIGKILL)
                    except ProcessLookupError:
                        pass
                    process.wait()
                output.write(f"\nInconclusive: command exceeded {timeout} seconds.\n")
                return 124


def version(command: list[str]) -> str:
    """Report tool identity without withholding evidence if a tool is absent."""
    try:
        result = subprocess.run(
            command, cwd=ROOT, capture_output=True, text=True, check=False, timeout=30
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        return str(error)
    return (result.stdout + result.stderr).strip()


def retained(target: str) -> list[pathlib.Path]:
    """Only committed semantic seeds feed deterministic PR replay."""
    paths = sorted((ROOT / "fuzz" / "seeds" / target).iterdir())
    if not paths or any(not path.is_file() or path.stat().st_size > MAX_INPUT for path in paths):
        raise ValueError(f"invalid or empty retained corpus for {target}")
    return paths


def generated(directory: pathlib.Path, seed: int, cases: int) -> list[pathlib.Path]:
    """Retain generated bytes separately so every failure has a replayable input."""
    directory.mkdir(parents=True, exist_ok=True)
    generator = random.Random(seed)
    lengths = (0, 1, 2, 7, 8, 39, 40, 41, 63, 64, 65, 255, MAX_INPUT)
    paths = []
    for index in range(cases):
        length = lengths[index] if index < len(lengths) else generator.randrange(MAX_INPUT + 1)
        path = directory / f"{index:05}.bin"
        path.write_bytes(generator.randbytes(length))
        paths.append(path)
    return paths


def digest(paths: list[pathlib.Path]) -> str:
    """Identify the precise ordered corpus independently of its filesystem path."""
    checksum = hashlib.sha256()
    for path in paths:
        data = path.read_bytes()
        checksum.update(len(data).to_bytes(8, "little"))
        checksum.update(data)
    return checksum.hexdigest()


def replay(args: argparse.Namespace, report: dict[str, object]) -> bool:
    """Exercise the actual pure production sources using the stable compiler."""
    output = args.output
    command = [
        "cargo",
        "build",
        "--manifest-path",
        "fuzz/Cargo.toml",
        "--locked",
        "--target-dir",
        "fuzz/target",
        "--bin",
        "replay",
    ]
    status = execute(command, output / "build.log")
    report["build_status"] = status
    if status:
        return False
    # A separate workspace is not covered by the root cargo-fmt invocation.
    status = execute(
        ["cargo", "fmt", "--manifest-path", "fuzz/Cargo.toml", "--check"], output / "format.log"
    )
    report["format_status"] = status
    if status:
        return False
    status = execute(
        [
            "cargo",
            "clippy",
            "--manifest-path",
            "fuzz/Cargo.toml",
            "--lib",
            "--bin",
            "replay",
            "--locked",
            "--target-dir",
            "fuzz/target",
            "--",
            "-D",
            "warnings",
        ],
        output / "clippy.log",
    )
    report["clippy_status"] = status
    if status:
        return False
    directory = output / "generated" / f"{args.seed}-{args.cases}"
    inputs = generated(directory, args.seed, args.cases)
    results = []
    report["targets"] = results
    success = True
    for target in TARGETS:
        seeds = retained(target)
        paths = seeds + inputs
        status = execute(
            [
                str(ROOT / "fuzz" / "target" / "debug" / "replay"),
                target,
                str(ROOT / "fuzz" / "seeds" / target),
                str(directory),
            ],
            output / f"{target}.log",
        )
        results.append(
            {
                "target": target,
                "retained": len(seeds),
                "generated": len(inputs),
                "sha256": digest(paths),
                "status": status,
            }
        )
        success = status == 0 and success
    return success


def campaign(args: argparse.Namespace, report: dict[str, object]) -> bool:
    """Instrument each target and retain evolving corpora and counterexamples."""
    output = args.output
    tool = version(["cargo", "fuzz", "--version"])
    report["cargo_fuzz"] = tool
    report["nightly"] = version(["rustup", "run", args.toolchain, "rustc", "-Vv"])
    if tool != f"cargo-fuzz {FUZZ_VERSION}":
        raise ValueError(f"expected cargo-fuzz {FUZZ_VERSION}; observed {tool}")
    # Managed hooks put a stable compiler directly on PATH. Select the pinned
    # nightly for nested cargo/rustc invocations as well as the outer command.
    nightly_cargo = pathlib.Path(
        subprocess.check_output(
            ["rustup", "which", "--toolchain", args.toolchain, "cargo"],
            text=True,
        ).strip()
    )
    environment = dict(os.environ)
    environment["PATH"] = str(nightly_cargo.parent) + os.pathsep + environment["PATH"]
    environment["RUSTC"] = str(nightly_cargo.with_name("rustc"))
    environment["RUSTUP_TOOLCHAIN"] = args.toolchain
    results = []
    report["targets"] = results
    success = True
    for target in TARGETS:
        corpus = output / "corpus" / target
        artifacts = output / "artifacts" / target
        corpus.mkdir(parents=True, exist_ok=True)
        artifacts.mkdir(parents=True, exist_ok=True)
        for source in retained(target):
            shutil.copyfile(source, corpus / source.name)
        # libFuzzer mutates valid structured examples and arbitrary bytes; every
        # target also constructs grammar-valid cases from the same bounded input.
        command = [
            "rustup",
            "run",
            args.toolchain,
            "cargo",
            "fuzz",
            "run",
            target,
            "--features",
            "fuzzing",
            "--",
            str(corpus),
            f"-artifact_prefix={artifacts}/",
            f"-max_total_time={args.seconds}",
            f"-seed={args.seed}",
            f"-max_len={MAX_INPUT}",
            "-timeout=10",
            "-rss_limit_mb=2048",
            "-print_final_stats=1",
        ]
        status = execute(
            command,
            output / f"{target}.log",
            timeout=args.seconds + 600,
            environment=environment,
        )
        paths = sorted(path for path in corpus.iterdir() if path.is_file())
        statistics = {
            key: int(value)
            for key, value in re.findall(
                r"stat::(\w+):\s+(\d+)", (output / f"{target}.log").read_text()
            )
        }
        results.append(
            {
                "target": target,
                "status": status,
                "corpus_count": len(paths),
                "corpus_sha256": digest(paths),
                "artifacts": str(artifacts),
                "statistics": statistics,
            }
        )
        success = status == 0 and statistics.get("number_of_executed_units", 0) > 0 and success
    return success


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("replay", "campaign"))
    parser.add_argument(
        "--seed", type=int, default=int(os.environ.get("GIT_PR_FUZZ_SEED", "20261015"))
    )
    parser.add_argument("--cases", type=int, default=256)
    parser.add_argument(
        "--seconds", type=int, default=int(os.environ.get("GIT_PR_FUZZ_SECONDS", "60"))
    )
    parser.add_argument("--toolchain", default=NIGHTLY)
    parser.add_argument("--output", type=pathlib.Path)
    args = parser.parse_args()
    if (
        not 1 <= args.cases <= 100_000
        or not 1 <= args.seconds <= 86_400
        or not 0 <= args.seed < 2**32
    ):
        parser.error("cases must be 1..100000, seconds must be 1..86400 and seed must fit u32")
    args.output = (args.output or ROOT / "target" / "validation" / "fuzz" / args.mode).resolve()
    previous = None
    if args.output.exists() and any(args.output.iterdir()):
        # Move only directories previously owned by this driver. An arbitrary
        # --output path must never cause unrelated files to be relocated.
        previous_report = args.output / "report.json"
        if not previous_report.is_file():
            parser.error("non-empty output directory has no fuzz report; select a dedicated path")
        previous_data = json.loads(previous_report.read_text())
        if previous_data.get("mode") not in ("replay", "campaign"):
            parser.error("output directory does not contain a recognised fuzz report")
        history = ROOT / "target" / "validation" / "history" / "fuzz"
        history.mkdir(parents=True, exist_ok=True)
        previous = history / f"{args.mode}-{time.time_ns()}"
        shutil.move(str(args.output), previous)
    args.output.mkdir(parents=True, exist_ok=True)
    report: dict[str, object] = {
        "mode": args.mode,
        "seed": args.seed,
        "max_input": MAX_INPUT,
        "cases": args.cases,
        "seconds_per_target": args.seconds,
        "python": sys.version,
        "rustc": version(["rustc", "-Vv"]),
        "git_head": version(["git", "rev-parse", "HEAD"]),
        "previous_evidence": str(previous) if previous else None,
        "source_sha256": {
            str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in [
                ROOT / "src" / "stack" / "description.rs",
                ROOT / "src" / "model" / "mod.rs",
                ROOT / "src" / "model" / "commit.rs",
                ROOT / "src" / "model" / "pull_request.rs",
                ROOT / "src" / "model" / "repository.rs",
                ROOT / "src" / "git" / "snapshot.rs",
                ROOT / "src" / "model" / "trailers.rs",
                ROOT / "fuzz" / "src" / "lib.rs",
                ROOT / "fuzz" / "Cargo.lock",
            ]
        },
    }
    started = time.monotonic()
    success = False
    try:
        success = replay(args, report) if args.mode == "replay" else campaign(args, report)
    except (OSError, ValueError) as error:
        report["error"] = str(error)
    finally:
        report["success"] = success
        report["elapsed_seconds"] = round(time.monotonic() - started, 3)
        path = args.output / "report.json"
        path.write_text(json.dumps(report, indent=2) + "\n")
        print(f"Fuzz {args.mode}: {'passed' if success else 'failed'}; evidence: {path}")
    return 0 if success else 1


if __name__ == "__main__":
    raise SystemExit(main())
